// fastify server (port 3000)

const fastify = require('fastify')({ logger: true })

fastify.get('/', async (request, reply) => {
    return { hello: 'world' }
})

// GET /fast — возвращает { message: 'I am fast' } мгновенно.
fastify.get('/fast', async (request, reply) => {
    return { message: 'I am fast' }
})

// GET /slow — выполняет синхронный тяжёлый цикл (сумма от 1 до 5 000 000 000), потом возвращает { result: ... }.
fastify.get('/slow', async (request, reply) => {
    let sum = 0;
    for (let i = 1; i <= 5000000000; i++) {
        sum += i;
    }
    return { result: sum }
})

// На данный момент при обращении к /slow сервер будет заблокирован на время выполнения цикла, 
// и другие запросы (например, к /fast) не будут обрабатываться, пока цикл не завершится.
// Это происходит из-за блокирования Event Loop, так как цикл выполняется синхронно и не позволяет другим задачам выполняться параллельно.
// {"message":"I am fast"}
// real	0m0,010s
// user	0m0,002s
// sys	0m0,008s

// При обращении к /fast, во время обращения к slow
// {"message":"I am fast"}
// real	0m4,200s
// user	0m0,002s
// sys	0m0,008s


// GET /fixslow -- вместо одного цикла на 5 млрд итераций — разбиваем на части (например, по 100 млн), между чанками отдаём управление Event Loop через setImmediate. 
// Это даёт Event Loop шанс обработать другие запросы между чанками.

fastify.get('/fixslow', async (request, reply) => {
    let sum = 0;
    const chunkSize = 100000000; // 100 млн
    const totalIterations = 5000000000; // 5 млрд

    for (let i = 1; i <= totalIterations; i++) {
        sum += i;
        if (i % chunkSize === 0) {
            await new Promise(resolve => setImmediate(resolve)); // Тут мы отдаем управление Event Loop, позволяя ему обрабатывать другие задачи в очереди
            console.log(`Processed ${i} iterations...`);
        }
    }
    return { result: sum }
})

// Теперь при обращении к /fixslow сервер не будет полностью заблокирован, и в периоды между чанками будут обрабатываться другие запросы
// При обращении к /fast, во время обращения к /fixslow:
// {"message":"I am fast"}
// real	0m2,016s //не моментально, но значительно быстрее, чем при обращении к /slow
// user	0m0,002s
// sys	0m0,003s


// Теперь при обращении к /fixslow сервер не будет полностью заблокирован, и другие запросы (например, к /fast) смогут обрабатываться между чанками, 
// так как мы отдаем управление Event Loop через setImmediate, позволяя ему обрабатывать другие задачи в очереди. 
// Это позволяет поддерживать отзывчивость сервера даже при выполнении тяжёлых операций.
// НО при этом общая производительность может снизиться из-за частых переключений контекста и увеличенного времени выполнения из-за пауз между чанками.
// Так же, предпорложительно, из-за отсутствия оптимизиции со стороны TurboFan

const start = async () => {
    try {
        await fastify.listen({ port: 3000 })
        console.log('Server is running on http://localhost:3000')
    } catch (err) {
        fastify.log.error(err)
        process.exit(1)
    }
}

start()

